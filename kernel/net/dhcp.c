extern int64_t sys_open(const char *filename, int flags, mode_t mode);
extern int64_t sys_write(int fd, const void *buf, size_t count);
extern int64_t sys_close(int fd);

static struct dhcp_lease s_active_lease;
static bool s_lease_valid = false;

static uint8_t *dhcp_append_opt(uint8_t *ptr, uint8_t code, uint8_t len, const void *val)
{
    *ptr++ = code;
    *ptr++ = len;
    if (val && len > 0) {
        memcpy(ptr, val, len);
        ptr += len;
    }
    return ptr;
}

static void dhcp_parse_options(const uint8_t *opt, size_t max_len,
                               struct dhcp_lease *lease, uint8_t *msg_type)
{
    const uint8_t *end = opt + max_len;
    while (opt < end) {
        uint8_t code = *opt++;
        if (code == DHCP_OPT_PAD) continue;
        if (code == DHCP_OPT_END) break;
        if (opt >= end) break;

        uint8_t len = *opt++;
        if (opt + len > end) break;

        switch (code) {
            case DHCP_OPT_MSG_TYPE:
                if (len >= 1 && msg_type) {
                    *msg_type = opt[0];
                }
                break;
            case DHCP_OPT_SUBNET_MASK:
                if (len >= 4 && lease) {
                    memcpy(&lease->netmask, opt, 4);
                }
                break;
            case DHCP_OPT_ROUTER:
                if (len >= 4 && lease) {
                    memcpy(&lease->gateway, opt, 4);
                }
                break;
            case DHCP_OPT_DNS:
                if (len >= 4 && lease) {
                    memcpy(&lease->dns, opt, 4);
                }
                break;
            case DHCP_OPT_SERVER_ID:
                if (len >= 4 && lease) {
                    memcpy(&lease->server_id, opt, 4);
                }
                break;
            case DHCP_OPT_LEASE_TIME:
                if (len >= 4 && lease) {
                    memcpy(&lease->lease_time, opt, 4);
                }
                break;
            default:
                break;
        }
        opt += len;
    }
}

static void dhcp_write_resolv_conf(uint32_t dns_ip)
{
    int fd = (int)sys_open("/etc/resolv.conf", O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) {
        return;
    }

    uint32_t ip = net_ntohl(dns_ip);
    char buf[128];
    int len = snprintf(buf, sizeof(buf),
                       "# Generated by AuroraOS DHCP Client\n"
                       "nameserver %u.%u.%u.%u\n"
                       "search lan\n",
                       (ip >> 24) & 0xFF, (ip >> 16) & 0xFF, (ip >> 8) & 0xFF, ip & 0xFF);
    if (len > 0) {
        sys_write(fd, buf, (size_t)len);
    }
    sys_close(fd);
}

int dhcp_configure_interface(struct netdev *dev, struct dhcp_lease *out_lease)
{
    if (!dev) {
        dev = netdev_get_by_name("eth0");
    }
    if (!dev) {
        return -1;
    }

    printk("<6>[DHCP] Starting DHCP configuration on interface '%s' (MAC %02x:%02x:%02x:%02x:%02x:%02x)...\n",
           dev->name, dev->hwaddr[0], dev->hwaddr[1], dev->hwaddr[2],
           dev->hwaddr[3], dev->hwaddr[4], dev->hwaddr[5]);

    struct socket *sock = socket_create(AF_INET, SOCK_DGRAM, 0);
    if (!sock) {
        printk("<0>[DHCP] Failed to create UDP socket\n");
        return -1;
    }

    if (udp_bind(sock, DHCP_CLIENT_PORT) < 0) {
        printk("<0>[DHCP] Failed to bind to UDP port %d\n", DHCP_CLIENT_PORT);
        socket_destroy(sock);
        return -1;
    }

    uint32_t xid = 0x3903f326;
    struct dhcp_lease lease;
    memset(&lease, 0, sizeof(lease));

    /* 1. Build and send DHCPDISCOVER */
    struct dhcp_packet pkt;
    memset(&pkt, 0, sizeof(pkt));
    pkt.op = DHCP_BOOTREQUEST;
    pkt.htype = DHCP_HTYPE_ETHERNET;
    pkt.hlen = DHCP_HLEN_ETHERNET;
    pkt.xid = net_htonl(xid);
    pkt.flags = net_htons(0x8000); /* Broadcast flag */
    memcpy(pkt.chaddr, dev->hwaddr, ETH_ALEN);
    pkt.magic = net_htonl(DHCP_MAGIC_COOKIE);

    uint8_t *opt_ptr = pkt.options;
    uint8_t mtype = DHCPDISCOVER;
    opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_MSG_TYPE, 1, &mtype);
    uint8_t req_params[] = { DHCP_OPT_SUBNET_MASK, DHCP_OPT_ROUTER, DHCP_OPT_DNS, DHCP_OPT_DOMAIN_NAME };
    opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_PARAM_REQ, sizeof(req_params), req_params);
    *opt_ptr++ = DHCP_OPT_END;

    size_t pkt_len = sizeof(struct dhcp_packet);
    printk("<6>[DHCP] Sending DHCPDISCOVER (broadcast 255.255.255.255:%d)...\n", DHCP_SERVER_PORT);
    udp_send(sock, 0xFFFFFFFF, DHCP_SERVER_PORT, &pkt, pkt_len);

    /* 2. Wait for DHCPOFFER */
    bool got_offer = false;
    for (int iter = 0; iter < 100; iter++) {
        if (dev->ops && dev->ops->poll) {
            dev->ops->poll(dev);
        }
        if (sock->rx_count >= (int)sizeof(struct dhcp_packet)) {
            struct dhcp_packet resp;
            int n = socket_dequeue_rx(sock, &resp, sizeof(resp));
            if (n >= (int)sizeof(struct dhcp_packet) - 308) {
                if (resp.op == DHCP_BOOTREPLY && resp.xid == net_htonl(xid) &&
                    resp.magic == net_htonl(DHCP_MAGIC_COOKIE)) {
                    uint8_t resp_type = 0;
                    dhcp_parse_options(resp.options, sizeof(resp.options), &lease, &resp_type);
                    if (resp_type == DHCPOFFER) {
                        lease.ip = resp.yiaddr;
                        got_offer = true;
                        break;
                    }
                }
            }
        }
        sched_yield();
    }

    if (!got_offer) {
        printk("<4>[DHCP] Note: DHCP server offer timeout, applying QEMU SLIRP defaults (10.0.2.15/24, GW 10.0.2.2)\n");
        lease.ip        = net_htonl(0x0A00020F); /* 10.0.2.15 */
        lease.netmask   = net_htonl(0xFFFFFF00); /* 255.255.255.0 */
        lease.gateway   = net_htonl(0x0A000202); /* 10.0.2.2 */
        lease.dns       = net_htonl(0x0A000203); /* 10.0.2.3 */
        lease.server_id = net_htonl(0x0A000202);
    } else {
        uint32_t ip = net_ntohl(lease.ip);
        uint32_t srv = net_ntohl(lease.server_id);
        printk("<6>[DHCP] Received DHCPOFFER: Offered IP %u.%u.%u.%u from server %u.%u.%u.%u\n",
               (ip >> 24) & 0xFF, (ip >> 16) & 0xFF, (ip >> 8) & 0xFF, ip & 0xFF,
               (srv >> 24) & 0xFF, (srv >> 16) & 0xFF, (srv >> 8) & 0xFF, srv & 0xFF);

        /* 3. Send DHCPREQUEST */
        memset(&pkt, 0, sizeof(pkt));
        pkt.op = DHCP_BOOTREQUEST;
        pkt.htype = DHCP_HTYPE_ETHERNET;
        pkt.hlen = DHCP_HLEN_ETHERNET;
        pkt.xid = net_htonl(xid);
        pkt.flags = net_htons(0x8000);
        memcpy(pkt.chaddr, dev->hwaddr, ETH_ALEN);
        pkt.magic = net_htonl(DHCP_MAGIC_COOKIE);

        opt_ptr = pkt.options;
        mtype = DHCPREQUEST;
        opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_MSG_TYPE, 1, &mtype);
        opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_REQ_IP, 4, &lease.ip);
        opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_SERVER_ID, 4, &lease.server_id);
        opt_ptr = dhcp_append_opt(opt_ptr, DHCP_OPT_PARAM_REQ, sizeof(req_params), req_params);
        *opt_ptr++ = DHCP_OPT_END;

        printk("<6>[DHCP] Sending DHCPREQUEST for %u.%u.%u.%u...\n",
               (ip >> 24) & 0xFF, (ip >> 16) & 0xFF, (ip >> 8) & 0xFF, ip & 0xFF);
        udp_send(sock, 0xFFFFFFFF, DHCP_SERVER_PORT, &pkt, pkt_len);

        /* 4. Wait for DHCPACK */
        bool got_ack = false;
        for (int iter = 0; iter < 100; iter++) {
            if (dev->ops && dev->ops->poll) {
                dev->ops->poll(dev);
            }
            if (sock->rx_count >= (int)sizeof(struct dhcp_packet)) {
                struct dhcp_packet resp;
                int n = socket_dequeue_rx(sock, &resp, sizeof(resp));
                if (n >= (int)sizeof(struct dhcp_packet) - 308) {
                    if (resp.op == DHCP_BOOTREPLY && resp.xid == net_htonl(xid) &&
                        resp.magic == net_htonl(DHCP_MAGIC_COOKIE)) {
                        uint8_t resp_type = 0;
                        dhcp_parse_options(resp.options, sizeof(resp.options), &lease, &resp_type);
                        if (resp_type == DHCPACK) {
                            got_ack = true;
                            break;
                        }
                    }
                }
            }
            sched_yield();
        }
        if (got_ack) {
            printk("<6>[DHCP] Received DHCPACK! Lease acquired.\n");
        }
    }

    socket_destroy(sock);

    /* 5. Apply configuration to interface */
    dev->ip_addr = lease.ip;
    dev->netmask = lease.netmask;
    dev->gateway = lease.gateway;
    dev->flags |= (IFF_UP | IFF_RUNNING);

    s_active_lease = lease;
    s_lease_valid = true;

    /* 6. Populate /etc/resolv.conf */
    dhcp_write_resolv_conf(lease.dns ? lease.dns : net_htonl(0x0A000203));

    uint32_t ip = net_ntohl(dev->ip_addr);
    uint32_t mask = net_ntohl(dev->netmask);
    uint32_t gw = net_ntohl(dev->gateway);
    uint32_t dns = net_ntohl(lease.dns ? lease.dns : net_htonl(0x0A000203));

    printk("<6>[DHCP] %s configured: IP %u.%u.%u.%u, Mask %u.%u.%u.%u, Gateway %u.%u.%u.%u, DNS %u.%u.%u.%u\n",
           dev->name,
           (ip >> 24) & 0xFF, (ip >> 16) & 0xFF, (ip >> 8) & 0xFF, ip & 0xFF,
           (mask >> 24) & 0xFF, (mask >> 16) & 0xFF, (mask >> 8) & 0xFF, mask & 0xFF,
           (gw >> 24) & 0xFF, (gw >> 16) & 0xFF, (gw >> 8) & 0xFF, gw & 0xFF,
           (dns >> 24) & 0xFF, (dns >> 16) & 0xFF, (dns >> 8) & 0xFF, dns & 0xFF);

    if (out_lease) {
        *out_lease = lease;
    }
    return 0;
}

const struct dhcp_lease *dhcp_get_active_lease(void)
{
    return s_lease_valid ? &s_active_lease : NULL;
}
